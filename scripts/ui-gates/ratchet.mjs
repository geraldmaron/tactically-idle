// The UI debt baseline: src/ui/ui-debt.json holds every ratchet's count, keyed by rule and then by
// file (static rules) or by surface and width (rendered rules). Only `npm run ui:baseline` writes it.
// A gate fails when a count rises (new debt) and when it falls without a regenerated baseline (debt
// paid is locked in). Rules whose goal is zero say so with `target: 0`; they start at today's count.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const BASELINE_FILE = 'src/ui/ui-debt.json';
const NOTE = 'Generated by `npm run ui:baseline`. Never edit by hand: the lead regenerates it at each merge and reads the diff. A count may only fall, and a fall has to be written here in the same commit.';

export function readBaseline(root) {
  const path = join(root, BASELINE_FILE);
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : { static: {}, rendered: {} };
}

/** Rules with nothing to pay down are left out of the file: an absent rule means zero. */
export function entry(counts, target = 0) {
  const sorted = Object.fromEntries(Object.entries(counts).filter(([, n]) => n > 0).sort(([a], [b]) => a.localeCompare(b)));
  return { target, total: Object.values(sorted).reduce((a, b) => a + b, 0), counts: sorted };
}

export function writeBaseline(root, baseline) {
  const sortObject = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
  const body = { _: NOTE, static: sortObject(baseline.static), rendered: sortObject(baseline.rendered) };
  writeFileSync(join(root, BASELINE_FILE), `${JSON.stringify(body, null, 1)}\n`);
}

/**
 * Compare one rule's current counts with its baseline counts.
 * @param {Record<string, number>} current  @param {Record<string, number> | undefined} base
 * @param {{ only?: (key: string) => boolean }} [options] limit the check to the keys a partial run covers
 * @returns {{ rose: string[], fell: string[] }}
 */
export function compareCounts(current, base = {}, options = {}) {
  const keys = new Set([...Object.keys(current), ...Object.keys(base)]);
  const rose = [], fell = [];
  for (const key of [...keys].sort()) {
    if (options.only && !options.only(key)) continue;
    const now = current[key] ?? 0, was = base[key] ?? 0;
    if (now > was) rose.push(`${key}: ${was} -> ${now}`);
    else if (now < was) fell.push(`${key}: ${was} -> ${now}`);
  }
  return { rose, fell };
}

export const RAISED_HELP = 'New debt: fix it, or ask the lead to accept it. Never raise the baseline by hand.';
export const FELL_HELP = 'Debt paid: run `npm run ui:baseline` and commit src/ui/ui-debt.json so it stays paid.';
